export default function PhoneInput({ value, onChange }) {
  // value is the full string like "+1 555-000-0000"
  // Parse stored value into countryCode + number
  const parseValue = (v) => {
    if (!v) return { countryCode: '+1', number: '' };
    const match = COUNTRY_CODES.find(c => v.startsWith(c.code + ' '));
    if (match) return { countryCode: match.code, number: v.slice(match.code.length + 1) };
    // fallback: try to find code at start
    const codeMatch = COUNTRY_CODES.find(c => v.startsWith(c.code));
    if (codeMatch) return { countryCode: codeMatch.code, number: v.slice(codeMatch.code.length).trim() };
    return { countryCode: '+1', number: v };
  };

  const { countryCode, number } = parseValue(value);

  const handleCodeChange = (e) => {
    onChange(`${e.target.value} ${number}`);
  };

  const handleNumberChange = (e) => {
    onChange(`${countryCode} ${e.target.value}`);
  };

  return (
    <div className="flex gap-2">
      <select
        value={countryCode}
        onChange={handleCodeChange}
        className="bg-black/30 border border-violet-500/20 rounded-xl px-3 py-2.5 text-sm text-white focus:outline-none focus:border-violet-500/60 w-56 flex-shrink-0"
      >
        {COUNTRY_CODES.map((c, i) => (
          <option key={`${c.code}-${c.country}`} value={c.code}>
            {c.flag} {c.code} {c.country}
          </option>
        ))}
      </select>
      <input
        type="tel"
        value={number}
        onChange={handleNumberChange}
        placeholder={PHONE_PLACEHOLDERS[countryCode] || '123 456 7890'}
        className="flex-1 bg-black/30 border border-violet-500/20 rounded-xl px-4 py-2.5 text-sm text-white placeholder-white/25 focus:outline-none focus:border-violet-500/60"
      />
    </div>
  );
}